package Datatype;

public class Variables 
{
	public static void main(String args[])
	{
		byte b= 43;
		short s= 300;
		int i = 98764;
		float f= 45.7f;
		double d= 78.98;
		
		System.out.println(b);
		System.out.println(s);
		System.out.println(i);
		System.out.println(f);
		System.out.println(d);
		
	}

}
